import Link from 'next/link';

import { Card } from '@/components/ui/card';
import { prisma } from '@/lib/prisma';
import { listedWhere } from '@/lib/practitioner-indexer';
import { loadRecruiterEarnings, type EarningsDb } from '@/lib/affiliate-earnings';

const usd = (cents: number) => `$${(cents / 100).toFixed(2)}`;

const joined = (d: Date | null) =>
  d
    ? new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' }).format(d)
    : null;

/**
 * "Practitioners you brought in" (spec v1.5 section 5) — the RECRUITER's dashboard card.
 *
 * Own profile only: the caller passes `isOwner`, and a non-owner (an admin looking at somebody
 * else's page) gets nothing, because this is that person's earnings, not the operator's. The
 * operator has the admin view. The query is scoped by `practitionerId` alone, which the edit page
 * takes from the profile it has already authorised, never from a request parameter.
 *
 * It renders nothing for someone who has brought nobody in and has earned nothing. That is also
 * what keeps the RECRUITED practitioner's dashboard silent about the affiliate share (section 5):
 * the only ledger rows this loads are the ones where this practitioner is the RECRUITER, so the
 * rows generated by their own sessions are never read here.
 *
 * Amounts are the ledger's, as recorded; payouts are not active yet while
 * `WHOP_TRANSFERS_ENABLED` is not 'true', and the card says so.
 *
 * TIMING: each share is credited to the recruiter's Whop balance as the client payment clears.
 * A refund that arrives AFTER a share was claimed for transfer is shown here as an "adjusted for a
 * refund" line: an open balance netted off the next transfer, and what has already been netted.
 */
export async function RecruitedPractitionersSection({
  practitionerId,
  isOwner,
  db = prisma as unknown as EarningsDb,
}: {
  practitionerId: string;
  isOwner: boolean;
  db?: EarningsDb;
}) {
  if (!isOwner) return null;

  const earnings = await loadRecruiterEarnings(db, practitionerId, listedWhere());
  const total = earnings.accruedUsdCents + earnings.settledUsdCents + earnings.refundBalanceOpenUsdCents;
  if (earnings.recruits.length === 0 && total === 0) return null;

  const payoutsActive = process.env.WHOP_TRANSFERS_ENABLED === 'true';

  return (
    <Card id="brought-in" className="scroll-mt-24 space-y-3 p-4 sm:p-5">
      <h2 className="text-sm font-semibold">Practitioners you brought in</h2>
      <p className="text-xs text-muted-foreground">
        You earn an affiliate share of the client payments that go through Natural Health Pros for each
        practitioner who joined with your link.
      </p>

      <dl className="grid grid-cols-2 gap-2 text-center">
        <div className="rounded-md border p-2">
          <dt className="text-[11px] text-muted-foreground">Accrued</dt>
          <dd className="text-sm font-semibold" data-testid="affiliate-accrued">
            {usd(earnings.accruedUsdCents)}
          </dd>
        </div>
        <div className="rounded-md border p-2">
          <dt className="text-[11px] text-muted-foreground">Paid</dt>
          <dd className="text-sm font-semibold" data-testid="affiliate-settled">
            {usd(earnings.settledUsdCents)}
          </dd>
        </div>
      </dl>
      <p className="text-[11px] leading-relaxed text-muted-foreground" data-testid="affiliate-timing-note">
        Your share is credited to your Whop balance as each client payment clears. Accrued is owed to you and is
        credited once payouts are live and your Whop account is verified. Withdrawing from your Whop balance is
        subject to Whop&apos;s own terms.
        {!payoutsActive && ' (payouts are not active yet)'}
      </p>
      {(earnings.refundBalanceOpenUsdCents > 0 || earnings.refundAdjustments.length > 0) && (
        <div className="space-y-2 rounded-md border p-3" data-testid="affiliate-refund-adjustments">
          <h3 className="text-xs font-semibold">Adjusted for a refund</h3>
          <p className="text-[11px] leading-relaxed text-muted-foreground">
            When a client payment is refunded after your share of it was credited, that amount is taken off your next
            transfer rather than collected from you.
          </p>
          <dl className="grid grid-cols-2 gap-2 text-center">
            <div className="rounded-md border p-2">
              <dt className="text-[11px] text-muted-foreground">Still to be taken off</dt>
              <dd className="text-sm font-semibold" data-testid="affiliate-refund-open">
                {usd(earnings.refundBalanceOpenUsdCents)}
              </dd>
            </div>
            <div className="rounded-md border p-2">
              <dt className="text-[11px] text-muted-foreground">Already taken off</dt>
              <dd className="text-sm font-semibold" data-testid="affiliate-refund-applied">
                {usd(earnings.refundAdjustedUsdCents)}
              </dd>
            </div>
          </dl>
          <ul className="divide-y rounded-md border text-[11px]">
            {earnings.refundAdjustments.map((a, i) => (
              <li key={i} className="flex items-center justify-between gap-3 px-3 py-1.5">
                <span>{joined(a.createdAt)}: refund adjustment {usd(a.amountUsdCents)}</span>
                <span className="text-muted-foreground">
                  {a.state === 'APPLIED' ? 'fully taken off' : `${usd(a.appliedUsdCents)} taken off so far`}
                </span>
              </li>
            ))}
          </ul>
        </div>
      )}
      {earnings.paidBreakdownCount > 0 && (
        <dl className="grid grid-cols-3 gap-2 text-center" data-testid="affiliate-paid-breakdown">
          <div className="rounded-md border p-2">
            <dt className="text-[11px] text-muted-foreground">Share</dt>
            <dd className="text-sm font-semibold" data-testid="affiliate-paid-gross">
              {usd(earnings.paidGrossUsdCents)}
            </dd>
          </div>
          <div className="rounded-md border p-2">
            <dt className="text-[11px] text-muted-foreground">Adjusted for a refund</dt>
            <dd className="text-sm font-semibold" data-testid="affiliate-paid-adjusted">
              {usd(earnings.paidAdjustedUsdCents)}
            </dd>
          </div>
          <div className="rounded-md border p-2">
            <dt className="text-[11px] text-muted-foreground">Credited to your balance</dt>
            <dd className="text-sm font-semibold" data-testid="affiliate-paid-net">
              {usd(earnings.paidNetUsdCents)}
            </dd>
          </div>
        </dl>
      )}

      {earnings.recruits.length > 0 && (
        <ul className="divide-y rounded-md border text-sm">
          {earnings.recruits.map((r) => (
            <li key={r.id} className="flex items-center justify-between gap-3 px-3 py-2">
              <div className="min-w-0">
                <Link href={`/practitioners/${r.slug}`} className="truncate font-medium hover:underline">
                  {r.displayName || r.slug}
                </Link>
                {joined(r.recruitedAt) && (
                  <p className="text-[11px] text-muted-foreground">Joined {joined(r.recruitedAt)}</p>
                )}
              </div>
              <span className="shrink-0 text-[11px] text-muted-foreground">
                {r.published ? 'Published' : 'Not published yet'}
              </span>
            </li>
          ))}
        </ul>
      )}
    </Card>
  );
}
